"""Extract a read-only camera adapter from the unchanged standalone Fast source.

Consumers share FB25Data and Fast's published binding cache. They never define
Fast controls, create/import its bank, rename meshes or recover a writer edit.
"""
from pathlib import Path
import hashlib
import re

ROOT = Path(__file__).resolve().parents[1]
FAST_ROOT = ROOT.parent / 'Camera Bank Fast'
FAST_SOURCE = FAST_ROOT / 'CameraBankFast25.txt'
if not FAST_SOURCE.exists():
    FAST_SOURCE = ROOT / 'Development/fast_camera_reference.txt'
OUTPUT = ROOT / 'Development/camera_reader.inc'


def routine(text, name):
    start = text.index('[RoutineDef,' + name + ',')
    depth = 0
    quote = comment = False
    for end in range(start, len(text)):
        char = text[end]
        if comment:
            if char == '\n': comment = False
            continue
        if not quote and text[end:end + 2] == '//': comment = True; continue
        if char == '"': quote = not quote
        if not quote:
            if char == '[': depth += 1
            elif char == ']':
                depth -= 1
                if depth == 0: return text[start:end + 1]
    raise ValueError(name)


def schema(fast_source=FAST_SOURCE):
    text = Path(fast_source).read_text(encoding='ascii')
    cells = set(re.findall(r'\[MVarDef,\s*FB25Data,\s*(\d+)', text))
    versions = set(re.findall(r'\[MVarSet,\s*FB25Data,\s*1,\s*(\d+)\s*\]', text))
    if len(cells) != 1 or len(versions) != 1:
        raise ValueError('Review the Camera Bank Fast allocation/version contract.')
    return int(cells.pop()) * 4, int(versions.pop())


def compose(fast_source=FAST_SOURCE):
    source = Path(fast_source).read_text(encoding='ascii')
    schema(fast_source)
    definitions = {name: routine(source, name)
                   for name in re.findall(r'\[RoutineDef,(\w+),', source)}
    # A consumer must ask the writer to finish either kind of transaction.
    ready = '''[RoutineDef,FB325_RequireFastReady,
    [If,(([MemGetSize,FBFTxn]>0)||([MemGetSize,FBFOriginal]>0))||(([MemGetSize,FB32RenameState]>0)||([MemGetSize,FB32OriginalBank]>0)),
        [MessageOK,"A Camera Bank Fast update is pending. Press a Fast camera button on the same Tool to finish recovery before exporting.","Camera Bank Fast"][Exit]
    ]
]
'''
    definitions['FB325_RequireFastReady'] = ready
    definitions['FB32_RequireVisibility'] = definitions['FB32_RequireVisibility'].replace(
        '[RoutineDef,FB32_RequireVisibility,',
        '[RoutineDef,FB32_RequireVisibility,\n    [RoutineCall,FB325_RequireFastReady]', 1)
    definitions['FB29_LoadSlot'] = definitions['FB29_LoadSlot'].replace(
        '[RoutineCall,FB32_Recover]', '')
    needed = set()
    def include(name):
        if name in needed: return
        needed.add(name)
        for called in re.findall(r'\[RoutineCall,\s*(\w+)', definitions[name]):
            include(called)
    for name in ('FB29_LoadSlot', 'FB32_VisibleNow'):
        include(name)
    forbidden = {'FB32_Recover', 'FB29_CreateEmptyBank', 'FB32_RefreshIdentifiers',
                 'FB32_Rename', 'FB32_BeginTransaction', 'FBF_FullBegin'}
    if needed & forbidden:
        raise ValueError('A camera-reader dependency unexpectedly writes/recoveries the Fast bank.')
    routines = '\n\n'.join(definitions[name] for name in definitions if name in needed)
    # Do not carry writer-only arrays into each consumer: ZScript has a finite
    # script-variable budget. Keep only declared globals referenced by readers.
    identifiers = set(re.findall(r'\b[A-Za-z_]\w*\b', routines))
    declarations = re.findall(r'^\[VarDef,[^\n]+', source, re.M)
    globals_ = '\n'.join(declaration for declaration in declarations
                        if re.match(r'\[VarDef,(\w+)', declaration)[1] in identifiers)
    body = globals_ + '\n\n' + routines
    shared = {'FB25Data', 'FBFCache', 'FBFTxn', 'FBFOriginal',
              'FB32LegacyState', 'FB32LegacyNames', 'FB32RenameState', 'FB32OriginalBank'}
    def token(match):
        word = match[0]
        if word.startswith(('"', '//')) or word in shared: return word
        if word in definitions: return 'RC_CB' + word[2:]
        if word.startswith('FB'): return 'RC' + word
        if word.startswith('fb'): return 'cb' + word[2:]
        if word.startswith('fx'): return 'cbFast' + word[2:]
        return word
    body = re.sub(r'"[^"\n]*"|//[^\n]*|\b[A-Za-z_]\w*\b', token, body)
    digest = hashlib.sha256(Path(fast_source).read_bytes()).hexdigest()
    return ('// Read-only Camera Bank Fast adapter; generated by build_fast_reader.py.\n'
            '// Shared bank: FB25Data. No fallback to the legacy CB25Data bank.\n'
            f'// Unchanged Fast source SHA256: {digest}\n' + body + '\n')


def main():
    OUTPUT.write_text(compose(), encoding='ascii', newline='\n')
    print('Camera Bank Fast reader built; standalone Fast files unchanged.')


if __name__ == '__main__': main()
