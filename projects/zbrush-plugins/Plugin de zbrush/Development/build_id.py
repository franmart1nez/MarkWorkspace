"""Compose the ID plugin from the live shared reader and its owned body.

No installed application is read or modified. Re-run after Camera Bank merges.
The schema size/version come from its source, not a second schema definition.
"""
from pathlib import Path
import hashlib
import re

ROOT = Path(__file__).resolve().parents[1]
OUTPUT = ROOT / 'Generate and Export ID/GenerateExportID.txt'


def compose(root=ROOT, camera_root=None):
    # An explicit alternate root lets integration tests use pinned camera inputs
    # while keeping all editable ID sources and output in the owned package.
    camera_root = Path(camera_root) if camera_root is not None else root
    camera = (camera_root / 'Camera Bank/CameraBank25.txt').read_text(encoding='ascii')
    reader = (camera_root / 'Development/camera_reader.inc').read_text(encoding='ascii')
    body = (root / 'Development/id_body.txt').read_text(encoding='ascii')
    cells = set(re.findall(r'\[MVarDef,\s*CB25Data,\s*(\d+)', camera))
    versions = set(re.findall(r'\[MVarSet,\s*CB25Data,\s*1,\s*(\d+)\s*\]', camera))
    if len(cells) != 1 or len(versions) != 1:
        raise ValueError('Camera Bank allocation/version contract changed; review build_id.py.')
    cells = int(cells.pop())
    version = int(versions.pop())
    required = ['RC_CB29_LoadSlot', 'RC_CB32_RequireVisibility',
                'RC_CB32_VisibleNow', 'RC_CB30_Resize', 'RC_CB30_LensPaths']
    for name in required:
        if f'[RoutineDef,{name},' not in reader:
            raise ValueError(f'Shared camera reader API changed: missing {name}. Review ID adapter.')
    # Namespace code identifiers only. Do not alter UI strings or shared bank /
    # camera transaction markers. Local reader scratch memory belongs to ID.
    locals_ = {'base', 'slot', 'visBase', 'savedCount', 'currentCount', 'st',
               'savedState', 'savedEye', 'currentStatus', 'currentEye',
               'savedFolderEye', 'currentFolderEye'}
    def token(m):
        word = m[0]
        if word.startswith(('"', '//')):
            return word
        if word.startswith('RC_'):
            return 'ID_' + word[3:]
        if word.startswith('cb'):
            return 'idCam' + word[2:]
        if word in locals_:
            # Native 2023 rejects underscores in variable identifiers, even
            # though routine names accept them. Keep legacy locals distinct
            # from the cb -> idCam namespace without punctuation.
            return 'idReader' + word[0].upper() + word[1:]
        if word == 'CB32ReadView':
            return 'ID32ReadView'
        return word
    private_reader = re.sub(r'"[^"\n]*"|//[^\n]*|\b[A-Za-z_]\w*\b', token, reader)
    digest = hashlib.sha256(reader.encode('ascii')).hexdigest()
    header = ('// Generate and Export ID 3.2.0 - generated by Development/build_id.py\n'
              '// Native acceptance and limitations: Development/VERIFICATION_3.2.0.md.\n'
              f'// Shared reader SHA256: {digest}\n'
              f'[VarDef,idBankBytes,{cells*4}]\n'
              f'[VarDef,idBankVersion,{version}]\n')
    assembled = header + private_reader + '\n' + body
    return '\n'.join(line.rstrip() for line in assembled.splitlines()) + '\n'


def main(camera_root=None):
    output = compose(camera_root=camera_root)
    OUTPUT.parent.mkdir(parents=True, exist_ok=True)
    OUTPUT.write_text(output, encoding='ascii', newline='\n')
    print(f'Built {OUTPUT.relative_to(ROOT)} ({len(output)} bytes).')


if __name__ == '__main__':
    main()
